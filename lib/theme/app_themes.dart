class AppThemeSpec {
  const AppThemeSpec({
    required this.id,
    required this.name,
    required this.brightness,
    required this.primary,
    required this.background,
    required this.surface,
    required this.surfaceAlt,
    required this.border,
    required this.text,
    required this.muted,
    required this.diff,
  });

  final String id;
  final String name;
  final Brightness brightness;
  final Color primary, background, surface, surfaceAlt, border, text, muted;
  final DiffTheme diff;
}

